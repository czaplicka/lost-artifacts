export function getPersonnelVenue(mission) {
  const key=String(mission?.scene||'').trim().toLowerCase();
  const profile=PERSONNEL_VENUES[key];
  if(!profile)throw new Error(`Missing personnel profile for crime scene "${key}". Add an explicit profile instead of using unrelated jobs.`);
  return {...profile,scene:key,location:mission.location||profile.label};
}
export function getPersonnelCollections(mission) {
  const profile=getPersonnelVenue(mission);
  return profile.groups.map(id=>{
    const item=PERSONNEL_COLLECTIONS.find(c=>c.id===id);
    if(!item)throw new Error(`Missing personnel collection: ${id}`);
    return item;
  });
}
