export function parseLockpickPrice(value) {
  const text=String(value??'').trim();
  if(!/^[0-9]+$/.test(text))throw Error('Enter a positive whole-dollar price.');
  const price=Number(text);
  if(!Number.isSafeInteger(price)||price<1)throw Error('Enter a positive whole-dollar price.');
  return price;
}
export const ORIGINAL_STOCK = "import {INVENTORY_SHOPS} from './InventoryShops.js';\nexport const SPY_SHOP_STOCK=INVENTORY_SHOPS.spy.filter(v=>v.enabled!==false).map(v=>({...v}));";
export const LOCKPICK_STOCK = `import { INVENTORY_SHOPS } from './InventoryShops.js';
import { PI_LOCKPICK_PRODUCT } from './piLockpickProduct.js';

const configured = INVENTORY_SHOPS.spy;
const products = configured.filter(product => product.enabled !== false).map(product => ({ ...product }));
// An explicit configuration, including enabled:false, takes precedence.
const alreadyConfigured = configured.some(product => product.category === 'equipment' && product.key === 'lockpick');
export const SPY_SHOP_STOCK = alreadyConfigured ? products : [...products, { ...PI_LOCKPICK_PRODUCT }];
`;
export function planLockpickShop({catalogText,locationsText,stockText,productText}, chosenPrice) {
  const price=parseLockpickPrice(chosenPrice);
  const catalog=JSON.parse(catalogText);
  if(!catalog||typeof catalog!=='object'||Array.isArray(catalog))throw Error('Invalid item catalog.');
  const source=catalog.evidence?.lockpick,existing=catalog.equipment?.lockpick;
  if(source&&existing)throw Error('Two lockpick catalog entries exist. Nothing was installed.');
  const item=source||existing;
  if(item?.id!=='evidence_lockpick')throw Error('The expected existing Lockpick Set was not found.');
  if(catalog.equipment!=null&&(typeof catalog.equipment!=='object'||Array.isArray(catalog.equipment)))throw Error('Invalid equipment catalog.');
  const catalogChanged=!!source||item.type!=='tool';
  catalog.equipment={...(catalog.equipment||{}),lockpick:{...item,type:'tool'}};
  if(source)delete catalog.evidence.lockpick;
  const fields=[...locationsText.matchAll(/\blockpicksItemId\s*:\s*(null|'[^']*'|"[^"]*")/g)];
  if(fields.length!==1||!["null","'evidence_lockpick'",'"evidence_lockpick"'].includes(fields[0][1]))throw Error('Custom or missing lockpick route setting. Nothing was installed.');
  const locations=locationsText.replace(/(\blockpicksItemId\s*:\s*)(null|'[^']*'|"[^"]*")/,"$1'evidence_lockpick'");
  if(![ORIGINAL_STOCK.trim(),LOCKPICK_STOCK.trim()].includes(stockText.trim()))throw Error('Custom spyShopStock.js detected. It was not overwritten.');
  const marker='// PI lockpick offer — generated by install-pi-lockpicks-shop.mjs';
  if(productText!=null&&!productText.startsWith(marker+'\n'))throw Error('Custom piLockpickProduct.js detected. It was not overwritten.');
  const product=marker+`\nexport const PI_LOCKPICK_PRODUCT = Object.freeze({\n  category: 'equipment',\n  key: 'lockpick',\n  price: ${price}\n});\n`;
  return {price,files:{
    'assets/data/ItemsCatalog.json':catalogChanged?JSON.stringify(catalog,null,2)+'\n':catalogText,
    'config/TableForThreeLocations.js':locations,
    'config/spyShopStock.js':LOCKPICK_STOCK,
    'config/piLockpickProduct.js':product
  }};
}
