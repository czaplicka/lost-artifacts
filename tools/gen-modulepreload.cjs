#!/usr/bin/env node
// Writes <link rel="modulepreload"> tags for every module that main.js
// imports statically (directly or indirectly) into game.html.
//
// Without these hints the browser discovers modules one import level at a
// time, so online every level costs a full network round trip. With them it
// requests the whole startup graph in parallel.
//
// Run after adding, removing or moving static imports:
//   npm run build:preload
// Use --check to fail (exit 1) when game.html is out of date.

const fs = require('node:fs');
const path = require('node:path');
const acorn = require('acorn');

const ROOT = path.resolve(__dirname, '..');
const ENTRY = path.join(ROOT, 'main.js');
const HTML = path.join(ROOT, 'game.html');
const START = '<!-- modulepreload:start (generated by tools/gen-modulepreload.cjs) -->';
const END = '<!-- modulepreload:end -->';

function collectImports(ast) {
  const specs = [];

  (function visit(node) {
    if (!node || typeof node.type !== 'string') return;

    if (
      (node.type === 'ImportDeclaration' ||
        node.type === 'ExportAllDeclaration' ||
        node.type === 'ExportNamedDeclaration') &&
      node.source
    ) {
      specs.push(node.source.value);
    }

    for (const key of Object.keys(node)) {
      const child = node[key];
      if (Array.isArray(child)) child.forEach(visit);
      else if (child && typeof child === 'object') visit(child);
    }
  })(ast);

  return specs;
}

function buildGraph(entry) {
  const order = [];
  const seen = new Set();

  (function walk(file) {
    if (seen.has(file)) return;
    seen.add(file);

    const source = fs.readFileSync(file, 'utf8');
    const ast = acorn.parse(source, {
      ecmaVersion: 'latest',
      sourceType: 'module'
    });

    for (const spec of collectImports(ast)) {
      // Only local files; CDN modules are left to the browser.
      if (!spec.startsWith('.')) continue;

      const target = path.resolve(path.dirname(file), spec);

      if (!fs.existsSync(target)) {
        throw new Error(
          `${path.relative(ROOT, file)} imports missing file ${spec}`
        );
      }

      walk(target);
    }

    order.push(file);
  })(entry);

  return order;
}

function render(files, eol) {
  const lines = files
    .filter(file => file !== ENTRY)
    .map(file => {
      const href = './' + path.relative(ROOT, file).split(path.sep).join('/');
      return `    <link rel="modulepreload" href="${href}">`;
    });

  return [`    ${START}`, ...lines, `    ${END}`].join(eol);
}

const files = buildGraph(ENTRY);
const html = fs.readFileSync(HTML, 'utf8');
const block = render(files, html.includes('\r\n') ? '\r\n' : '\n');
const pattern = new RegExp(
  `[ \\t]*${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END}`
);

if (!pattern.test(html)) {
  console.error(`game.html is missing the markers:\n${START}\n${END}`);
  process.exit(1);
}

const next = html.replace(pattern, block);

if (process.argv.includes('--check')) {
  if (next !== html) {
    console.error('game.html modulepreload list is out of date. Run: npm run build:preload');
    process.exit(1);
  }
  console.log(`modulepreload list is up to date (${files.length - 1} modules).`);
} else {
  fs.writeFileSync(HTML, next);
  console.log(`Wrote ${files.length - 1} modulepreload links to game.html.`);
}
